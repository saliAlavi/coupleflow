#!/usr/bin/env python
"""Appendix table + macros: content groups recovered from the audio (App. C).

Reads ``<cache>/<ds>/unified_groups.json`` (written by ``coupleflow/preprocessing/stimulus_groups.py``) and,
if present, ``paper/tables/groups_null.json`` (best match of 10-s chunks
against *other* groups, the evidence that the 0.95 threshold separates copies from chance).
Writes ``tables/groups.tex`` and ``tables/numbers_groups.tex``.

    python scripts/tables/groups_table.py
"""

import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from coupleflow import paths  # noqa: E402

CACHE = paths.DATA
OUT = Path("paper/tables")
DS = [("kuleuven", "KU Leuven", "KUL"), ("dtu", "DTU", "DTU"), ("fuglsang2020", "Fuglsang'20", "Fug"),
      ("esaa", "ESAA", "ESAA"), ("uhd255", "KUL-255ch", "UHD"), ("broderick_cp", "Broderick", "Brod"),
      ("sparrkulee", "SparrKULee", "Sparr"), ("megmasc", "MEG-MASC", "MEG"), ("maestro", "MAESTRO", "Mae")]


def main() -> None:
    null = {}
    p = OUT / "groups_null.json"
    if p.exists():
        null = json.loads(p.read_text())
    rows, mac, minr = [], [], []
    for key, name, k in DS:
        gp = CACHE / key / "unified_groups_v2.json"
        gp = gp if gp.exists() else CACHE / key / "unified_groups.json"
        s = json.loads(gp.read_text())["stats"]
        sizes = {int(a): b for a, b in s["group_size_hist"].items()}
        single = sizes.get(1, 0)
        gps = sorted(set(s["groups_per_subject"].values()))
        gps_s = f"{gps[0]}" if len(gps) == 1 else f"{gps[0]}--{gps[-1]}"
        mr = s["min_verified_r"]
        minr.append(mr)
        nl = null.get(key, {})
        nl_s = f"{nl['max']:.2f} & {nl['max64']:.2f}" if nl else "-- & --"
        rows.append(f"{name} & {s['n_trials']} & {s['n_groups']} & {gps_s} & {single} & "
                    f"{s['n_verified_links']} & {mr:.3f} & {nl_s} \\\\")
        mac += [f"\\newcommand{{\\grp{k}Trials}}{{{s['n_trials']}}}",
                f"\\newcommand{{\\grp{k}Groups}}{{{s['n_groups']}}}"]
    mac.append(f"\\newcommand{{\\grpMinR}}{{{min(minr):.3f}}}")
    if null:
        mac.append(f"\\newcommand{{\\grpNullMaxCoarse}}{{{max(v['max'] for v in null.values()):.2f}}}")
        mac.append(f"\\newcommand{{\\grpNullMax}}{{{max(v['max64'] for v in null.values()):.2f}}}")
        mac.append(f"\\newcommand{{\\grpNullMed}}{{{max(v['median64'] for v in null.values()):.2f}}}")
    (OUT / "groups.tex").write_text(
        "\\begin{tabular}{lcccccccc}\\toprule\n"
        "& & & & & \\multicolumn{2}{c}{copies (links)} & \\multicolumn{2}{c}{best match, other groups}"
        " \\\\\n\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}\n"
        "Dataset & trials & groups & groups per listener & single-trial groups & number "
        "& min.\\ $r$ (64\\,Hz) & max.\\ $r$ (8\\,Hz) & max.\\ $r$ (64\\,Hz) \\\\\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\\end{tabular}\n")
    (OUT / "numbers_groups.tex").write_text(
        "% generated by scripts/tables/groups_table.py\n" + "\n".join(mac) + "\n")
    print((OUT / "groups.tex").read_text())


if __name__ == "__main__":
    main()
