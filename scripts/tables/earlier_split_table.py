#!/usr/bin/env python
"""Appendix table + macros: our earlier decoder under a within-trial window split vs. a
trial-disjoint split (App. E).

Source: ``results/earlier/split_protocol_comparison_strict.tex`` (the earlier
NeuroToken study; identical cache, subjects, 5-s window, folds and recipe, only the split
changes).  Columns used: ``attune-flow`` (the earlier flow decoder) and ``env-multi`` (its
envelope decoder).  Writes ``tables/earlier_split.tex`` and ``tables/numbers_earlier.tex``.

    python scripts/tables/earlier_split_table.py
"""

import re
from pathlib import Path

SRC = Path("results/earlier/split_protocol_comparison_strict.tex")
OUT = Path("paper/tables")
KEY = {"KU Leuven": "KUL", "DTU": "DTU", "NJU": "NJU"}


def main() -> None:
    txt = SRC.read_text()
    cols = [c.strip() for c in re.search(r"Dataset & Protocol & (.*?)\\\\", txt).group(1).split("&")]
    i_flow, i_env = cols.index("attune-flow"), cols.index("env-multi")
    res, ds = {}, None
    for line in txt.splitlines():
        m = re.search(r"\\multirow\{3\}\{\*\}\{(.+?) \((\d+)\), 5s\}", line)
        if m:
            ds = (m.group(1), int(m.group(2)))
        cells = [c.strip() for c in line.split("&")]
        if ds and len(cells) >= 3 and cells[1] in ("Segment", "Trial"):
            vals = [float(c.rstrip("\\ ").strip()) for c in cells[2:]]
            res.setdefault(ds, {})[cells[1]] = (vals[i_flow], vals[i_env])
    rows, mac = [], []
    for (name, n), r in res.items():
        (fs, es), (ft, et) = r["Segment"], r["Trial"]
        note = "$^a$" if name == "NJU" else ""
        rows.append(f"{name}{note} & {n} & {fs:.1f} & {ft:.1f} & {fs - ft:.1f} & "
                    f"{es:.1f} & {et:.1f} & {es - et:.1f} \\\\")
        k = KEY[name]
        mac += [f"\\newcommand{{\\oldSeg{k}}}{{{fs:.1f}}}", f"\\newcommand{{\\oldTrial{k}}}{{{ft:.1f}}}",
                f"\\newcommand{{\\oldDrop{k}}}{{{fs - ft:.1f}}}"]
    drops = [v for r in res.values() for v in (r["Segment"][0] - r["Trial"][0],
                                                   r["Segment"][1] - r["Trial"][1])]
    mac += [f"\\newcommand{{\\oldDropAllMin}}{{{min(drops):.1f}}}",
            f"\\newcommand{{\\oldDropAllMax}}{{{max(drops):.1f}}}"]
    (OUT / "earlier_split.tex").write_text(
        "\\begin{tabular}{lccccccc}\\toprule\n"
        "& & \\multicolumn{3}{c}{earlier flow decoder} & \\multicolumn{3}{c}{earlier envelope decoder}"
        " \\\\\n\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}\n"
        "Dataset & listeners & within-trial & trial-disj. & drop & within-trial & trial-disj. & drop"
        " \\\\\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\\end{tabular}\n")
    (OUT / "numbers_earlier.tex").write_text(
        "% generated by scripts/tables/earlier_split_table.py\n" + "\n".join(mac) + "\n")
    print(open(OUT / "earlier_split.tex").read())
    print("\n".join(mac))


if __name__ == "__main__":
    main()
