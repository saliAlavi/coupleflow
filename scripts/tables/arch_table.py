#!/usr/bin/env python
"""Parameter counts of CoupleFlow per module, read from the `final` checkpoints.

Writes paper/tables/arch.tex (module table) and
paper/tables/arch_numbers.tex (macros used in the text).

    python scripts/tables/arch_table.py
"""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from coupleflow import paths  # noqa: E402

import torch

RUNS = paths.RUNS / "final"
OUT = Path("paper/tables")
FULL, ENV_ONLY = "kuleuven", "fuglsang2020"          # all features / envelope-only
DATASETS = ["kuleuven", "dtu", "fuglsang2020", "esaa", "uhd255", "broderick_cp",
            "sparrkulee", "megmasc"]


def state(ds: str) -> dict[str, torch.Tensor]:
    ck = torch.load(RUNS / f"{ds}_fold0" / "best.pt", map_location="cpu", weights_only=False)
    ck = ck.get("model", ck)
    return ck.get("state_dict", ck)


def count(sd: dict, *prefixes: str) -> int:
    return sum(v.numel() for k, v in sd.items() if k.startswith(prefixes))


def fmt(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


if __name__ == "__main__":
    sd, sde = state(FULL), state(ENV_ONLY)
    per_listener = sd["U"][0].numel() + sd["V"][0].numel()
    rows = [  # (module, spec, output, keys)
        ("Listener correction", r"$x+U_m V_m^{\top}x$, rank 2, $U_m$ init.\ 0",
         r"$64\times L'$", None),
        ("Virtual sensors", r"$1{\times}1$ conv, $64\to8$", r"$8\times L'$", ("spatial.",)),
        ("EEG encoder", r"5 conv, kernel 3, dilation 1--16, width 32, GN+GELU, no padding",
         r"$16\times L$", ("eeg_enc.",)),
        ("Audio encoder (per $k$)", r"4 conv, kernel 3, dilation 1--8, width 32, causal, shared",
         r"$16\times L$", ("aud_enc.",)),
        ("Coupling score", r"weights $w_d$, temperature $\tau$", r"$K$", ("w", "log_tau")),
        ("Flow head", r"$1{\times}1$ in ($34\to64$), 5 residual dilated blocks, zero-init out",
         r"$1\times L$", ("flow.",)),
        ("Side head", r"$1{\times}1$ ($64\to16$), 4 dilated conv, mean/log-s.d., linear",
         r"2", ("side_",)),
        ("Audio adversary", r"MLP $32\to32\to1$ per candidate, gradient reversal", r"$K$", ("adv.",)),
        ("Envelope read-out", r"$1{\times}1$ conv, $16\to1$", r"$1\times L$", ("env_head.",)),
    ]
    lines = [r"\begin{tabular}{lp{0.43\textwidth}lr}\toprule",
             r"Module & Specification & Output & Parameters\\\midrule"]
    shared = 0
    for name, spec, out, keys in rows:
        if keys is None:
            p = rf"{fmt(per_listener)} / listener"
        else:
            n = count(sd, *keys)
            ne = count(sde, *keys)
            shared += n
            p = fmt(n) if n == ne else rf"{fmt(n)} ({fmt(ne)}$^\ast$)"
        lines.append(rf"{name} & {spec} & {out} & {p}\\")
    decision = count(sd, "spatial.", "eeg_enc.", "aud_enc.", "w", "log_tau")
    totals = {ds: sum(v.numel() for v in state(ds).values()) for ds in DATASETS}
    lines += [r"\midrule",
              rf"Shared total & & & {fmt(shared)}\\",
              rf"Decision path (coupling) & listener correction, virtual sensors, both encoders, "
              rf"score & & {fmt(decision)} + {fmt(per_listener)}/listener\\",
              r"\bottomrule\end{tabular}"]
    (OUT / "arch.tex").write_text("\n".join(lines) + "\n")
    mac = {"archPerListener": fmt(per_listener), "archShared": fmt(shared),
           "archDecision": fmt(decision), "archFlow": fmt(count(sd, "flow.")),
           "archAudIn": str(sd["aud_enc.net.0.weight"].shape[1]),
           "archAudInEnv": str(sde["aud_enc.net.0.weight"].shape[1]),
           "archTotMin": fmt(min(totals.values())), "archTotMax": fmt(max(totals.values()))}
    (OUT / "arch_numbers.tex").write_text(
        "% generated by scripts/tables/arch_table.py -- do not edit\n"
        + "".join(rf"\newcommand{{\{k}}}{{{v}}}" + "\n" for k, v in mac.items()))
    print((OUT / "arch.tex").read_text(), (OUT / "arch_numbers.tex").read_text(), totals)
