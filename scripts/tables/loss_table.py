#!/usr/bin/env python
"""Size of every weighted loss term during training (appendix on the objective).

For each dataset and each paper run (tags final, final_s1, final_s2; all folds) the training
history logs every term already multiplied by its weight. We report the mean over runs of
each term at the first epoch and at the selected (best) epoch, and the reference values a
term takes at chance: CE over K=2 candidates ln 2, InfoNCE over a batch of B windows ln B.

    python scripts/tables/loss_table.py   # -> paper/tables/loss_terms.tex
"""

from __future__ import annotations

import json
import math
import sys
import warnings
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from coupleflow.analysis.aggregate import ROOT  # noqa: E402

T = Path("paper/tables")
DS = [("kuleuven", "KU Leuven"), ("dtu", "DTU"), ("fuglsang2020", "Fuglsang'20"), ("esaa", "ESAA"),
      ("uhd255", "KUL-255ch"), ("broderick_cp", "Broderick"), ("sparrkulee", "SparrKULee"),
      ("megmasc", "MEG-MASC")]
TERMS = [("task", "$\\mathcal L_{\\rm CE}$"), ("con", "$\\mathcal L_{\\rm NCE}$"),
         ("null", "$\\mathcal L_{\\rm null}$"), ("col", "$\\mathcal L_{\\rm VIC}$"),
         ("adv", "$\\mathcal L_{\\rm adv}$"), ("flow", "$\\mathcal L_{\\rm FM}$"),
         ("side", "$\\mathcal L_{\\rm side}$"), ("env", "$\\mathcal L_{\\rm env}$")]
TAGS = ["final", "final_s1", "final_s2"]


def runs(ds: str) -> list[dict]:
    out = []
    for tag in TAGS:
        for d in sorted((ROOT / tag).glob(f"{ds}_fold*")):
            p = d / "results.json"
            if p.exists():
                r = json.loads(p.read_text())
                if "history" in r:                # validator-only results carry no history
                    out.append(r)
    return out


def f(x: float | None) -> str:
    return "--" if x is None or np.isnan(x) else f"{x:.2f}"


def main() -> None:
    warnings.filterwarnings("ignore", "Mean of empty slice")
    rows, summary = [], {}
    for ds, name in DS:
        rs = runs(ds)
        first = {k: [] for k, _ in TERMS}
        best = {k: [] for k, _ in TERMS}
        for r in rs:
            h = r["history"]
            hb = next((e for e in h if e["epoch"] == r["best_epoch"]), h[-1])
            for k, _ in TERMS:
                first[k].append(h[0]["train"].get(k, np.nan))
                best[k].append(hb["train"].get(k, np.nan))
        m0 = {k: float(np.nanmean(v)) if v else np.nan for k, v in first.items()}
        m1 = {k: float(np.nanmean(v)) if v else np.nan for k, v in best.items()}
        summary[ds] = {"first": m0, "best": m1, "n_runs": len(rs)}
        rows.append(f"{name} & first & " + " & ".join(f(m0[k]) for k, _ in TERMS) + " \\\\")
        rows.append(f" & selected & " + " & ".join(f(m1[k]) for k, _ in TERMS) + " \\\\")
    cfg = json.loads(json.dumps(runs("kuleuven")[0]["config"]))
    w, bs = cfg["losses"], cfg["optim"]["batch_size"]
    ref = {"task": math.log(2), "con": w["con"] * math.log(bs), "adv": w["adv"] * math.log(2),
           "side": w["side"] * math.log(2)}
    rows.append("\\midrule\nchance & & " + " & ".join(f(ref.get(k)) for k, _ in TERMS) + " \\\\")
    (T / "loss_terms.tex").write_text(
        "\\begin{tabular}{ll" + "c" * len(TERMS) + "}\\toprule\nDataset & epoch & "
        + " & ".join(n for _, n in TERMS) + " \\\\\\midrule\n" + "\n".join(rows)
        + "\n\\bottomrule\\end{tabular}\n")
    (T / "loss_terms.json").write_text(json.dumps({"summary": summary, "chance": ref,
                                                   "weights": w, "batch": bs}, indent=1))
    drop = [1 - v["best"]["con"] / v["first"]["con"] for v in summary.values()]
    (T / "numbers_loss.tex").write_text(
        "% generated by scripts/tables/loss_table.py\n"
        f"\\newcommand{{\\nceDropMin}}{{{100 * min(drop):.0f}}}\n"
        f"\\newcommand{{\\nceDropMax}}{{{100 * max(drop):.0f}}}\n")
    print((T / "loss_terms.tex").read_text())


if __name__ == "__main__":
    main()
