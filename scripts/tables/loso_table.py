#!/usr/bin/env python
"""LOSO table + macros (listener x content held out; ONE seed).

Rows: every dataset. Columns: CoupleFlow on the content-disjoint folds at 5 s (mean of 3
seeds, as in the main table), CoupleFlow LOSO (seed 0) at 1, 5 and 20 s with its
across-trial null at 5 s, and the pooled linear backward model under the same LOSO folds
(two-talker datasets, ``baselines/linear/linear_loso.py``). MEG-MASC uses the 208-sensor model
(its runs live in the same tags as every other dataset since 2026-09-30).
Writes ``paper/tables/loso.tex`` and ``tables/numbers_loso.tex``.

    python scripts/tables/loso_table.py
"""

import glob
import json
import os
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from coupleflow import paths  # noqa: E402

import numpy as np

R = str(paths.RUNS)
CACHE = paths.DATA
OUT = Path("paper/tables")
DS = [("kuleuven", "KU Leuven", "KUL"), ("dtu", "DTU", "DTU"), ("fuglsang2020", "Fuglsang'20", "Fug"),
      ("esaa", "ESAA", "ESAA"), ("uhd255", "KUL-255ch", "UHD"), ("broderick_cp", "Broderick", "Brod"),
      ("sparrkulee", "SparrKULee", "Sparr"), ("megmasc", "MEG-MASC$^a$", "MEG")]
ONE = {"sparrkulee", "megmasc"}


def pooled(tag: str, ds: str, cell: str, key: str = "acc_coupling") -> float | None:
    num = den = 0.0
    for d in glob.glob(f"{R}/{tag}/{ds}_fold*"):
        p = f"{d}/results.json" if os.path.exists(f"{d}/results.json") else f"{d}/results_val.json"
        if not os.path.exists(p):
            continue
        r = json.load(open(p))["results"].get(cell, {})
        if r.get("n_windows"):
            num += r[key] * r["n_windows"]
            den += r["n_windows"]
    return 100 * num / den if den else None


def f(x):
    return "--" if x is None else f"{x:.1f}"


def main() -> None:
    rows, mac, drops = [], [], []
    for ds, name, k in DS:
        task = "same_talker" if ds in ONE else "competing"
        cf_tags, lo_tag = ["final", "final_s1", "final_s2"], "loso_s0"
        cf = [pooled(t, ds, f"{task}_5s") for t in cf_tags]
        cf = float(np.mean(cf)) if all(c is not None for c in cf) else None
        lo = {W: pooled(lo_tag, ds, f"{task}_{W}s") for W in (1, 5, 20)}
        nul = pooled(lo_tag, ds, f"{task}_5s", "null_coupling")
        lp = CACHE / ds / "linear_loso.json"
        lin = 100 * json.loads(lp.read_text())["acc"] if lp.exists() else None
        rows.append(f"{name} & {f(cf)} & {f(lo[1])} & {f(lo[5])} & {f(lo[20])} & {f(nul)} & {f(lin)} \\\\")
        mac += [f"\\newcommand{{\\loso{k}Five}}{{{f(lo[5])}}}", f"\\newcommand{{\\loso{k}CF}}{{{f(cf)}}}"]
        if cf is not None and lo[5] is not None and ds != "broderick_cp":
            drops.append(cf - lo[5])
    # the abandoned per-listener PCA input for MEG-MASC (runs kept in <runs>/_pca_megmasc)
    pca = pooled("_pca_megmasc/loso_s0", "megmasc", "same_talker_5s")
    mac.append(f"\\newcommand{{\\losoMEGpca}}{{{f(pca)}}}")
    mac += [f"\\newcommand{{\\losoDropMin}}{{{min(drops):.1f}}}",
            f"\\newcommand{{\\losoDropMax}}{{{max(drops):.1f}}}"]
    (OUT / "loso.tex").write_text(
        "\\begin{tabular}{lcccccc}\\toprule\n"
        "& content folds & \\multicolumn{4}{c}{LOSO, CoupleFlow (1 seed)} & LOSO, linear \\\\\n"
        "\\cmidrule(lr){3-6}\n"
        "Dataset & 5\\,s & 1\\,s & 5\\,s & 20\\,s & null (5\\,s) & 5\\,s \\\\\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\\end{tabular}\n")
    (OUT / "numbers_loso.tex").write_text("% generated by scripts/tables/loso_table.py\n"
                                          + "\n".join(mac) + "\n")
    print((OUT / "loso.tex").read_text())


if __name__ == "__main__":
    main()
