#!/usr/bin/env python
"""Write paper/fig_net_encoders.tex: both encoders' receptive fields on one
time axis (App. D).  The trees are exact: an unpadded kernel-3 convolution with dilation d
makes node q of layer l+1 depend on q, q+d, q+2d of layer l (EEG, sliced to start delta
after the sound), and the causal audio convolutions make it depend on q, q-d, q-2d.

    python scripts/figures/fig_net_encoders.py
"""

from pathlib import Path

SR = 64
DX = 0.085          # cm per sample
DY = 0.36           # cm per layer
LAG = 8             # delta = 125 ms (samples)
EEG_D = [1, 2, 4, 8, 16]
AUD_D = [1, 2, 4, 8]
OUT = Path("paper/fig_net_encoders.tex")


def tree(root: int, dils: list[int], sign: int) -> list[list[int]]:
    """Unique node positions per layer, input layer first."""
    layers = [{root}]
    for d in reversed(dils):
        layers.append({q + sign * j * d for q in layers[-1] for j in range(3)})
    return [sorted(s) for s in reversed(layers)]


def draw(lines: list[str], root: int, dils: list[int], sign: int, up: int, col: str) -> None:
    lay = tree(root, dils, sign)
    y = lambda l: up * (0.35 + l * DY)                            # noqa: E731
    for l in range(len(dils)):
        d = dils[l]
        for q in lay[l + 1]:
            for j in range(3):
                p = q + sign * j * d
                lines.append(f"\\draw[{col},line width=0.25pt,opacity=0.55] "
                             f"({q * DX:.3f},{y(l + 1):.3f}) -- ({p * DX:.3f},{y(l):.3f});")
    for l, qs in enumerate(lay):
        r = 0.045 if l < len(lay) - 1 else 0.075
        for q in qs:
            lines.append(f"\\fill[{col}] ({q * DX:.3f},{y(l):.3f}) circle ({r}cm);")
    for l, d in enumerate(dils):
        x = (max(lay[l + 1]) if sign > 0 else min(lay[l + 1])) * DX
        anc = "west" if sign > 0 else "east"
        off = 0.18 if sign > 0 else -0.18
        lines.append(f"\\node[font=\\tiny,text={col},anchor={anc}] at ({x + off:.3f},{y(l + 1):.3f})"
                     f" {{$d{{=}}{d}$}};")


def main() -> None:
    L = [r"% App. D figure: receptive fields of both encoders on one time axis.",
         r"% Generated by scripts/figures/fig_net_encoders.py -- do not edit by hand.",
         r"\begin{tikzpicture}[x=1cm,y=1cm]"]
    rf_e = 2 * sum(EEG_D)                                        # 62 -> 63 samples
    rf_a = 2 * sum(AUD_D)                                        # 30 -> 31 samples
    lo, hi = -(LAG + rf_e) - 6, LAG + rf_e + 6
    # lag control (mirror window), drawn first so the trees lie on top
    a, b = -(LAG + rf_e) * DX, -LAG * DX
    L.append(f"\\fill[pattern=north east lines,pattern color=cfX!45] ({a:.3f},0.12) rectangle ({b:.3f},0.3);")
    L.append(f"\\node[font=\\tiny,text=cfX,anchor=south] at ({(a + b) / 2:.3f},0.32)"
             r" {lag control: EEG in $[t{-}\delta{-}0.98,\,t{-}\delta]$\,s (mirror; not used)};")
    # time axis
    L.append(f"\\draw[cfInk,line width=0.5pt,->] ({lo * DX:.3f},0) -- ({hi * DX:.3f},0)"
             r" node[right,font=\scriptsize] {time};")
    for s in (-1.0, -0.5, 0.5, 1.0):
        x = s * SR * DX
        L.append(f"\\draw[cfInk,line width=0.4pt] ({x:.3f},-0.06) -- ({x:.3f},0.06);")
        L.append(f"\\node[font=\\tiny,text=cfX] at ({x:.3f},-0.2) {{${s:+g}$\\,s}};")
    L.append(r"\draw[cfC,line width=1pt] (0,-0.25) -- (0,2.4);")
    L.append(r"\node[font=\scriptsize,text=cfC,anchor=south west,inner sep=1pt] at (0.04,0.05) {sound at $t$};")
    # EEG tree (above) and audio tree (below)
    draw(L, LAG, EEG_D, +1, +1, "cfN")
    draw(L, 0, AUD_D, -1, -1, "cfA")
    top = 0.35 + len(EEG_D) * DY
    bot = -(0.35 + len(AUD_D) * DY)
    L.append(f"\\draw[cfN,line width=0.6pt,->] ({LAG * DX:.3f},{top:.3f}) to[out=150,in=30,looseness=0.6]"
             f" ({0.05:.3f},{top + 0.02:.3f});")
    L.append(f"\\node[font=\\scriptsize,text=cfN,anchor=south east] at (0.0,{top:.3f}) {{$e_t$}};")
    L.append(f"\\node[font=\\scriptsize,text=cfA,anchor=north west] at (0.1,{bot:.3f}) {{$\\hat a_{{k,t}}$}};")
    # brackets
    xe0, xe1 = LAG * DX, (LAG + rf_e) * DX
    L.append(f"\\draw[cfN,line width=0.6pt,|-|] ({xe0:.3f},{top + 0.42:.3f}) -- ({xe1:.3f},{top + 0.42:.3f})"
             r" node[midway,above,font=\scriptsize,align=center]"
             r" {EEG encoder: 5 unpadded convs, kernel 3; receptive field 63 samples (0.98\,s),"
             r" \\ sliced to EEG in $[t{+}\delta,\,t{+}\delta{+}0.98]$\,s after the sound};")
    L.append(f"\\draw[cfN,line width=0.4pt,<->] (0,{top + 0.1:.3f}) -- ({xe0:.3f},{top + 0.1:.3f})"
             r" node[midway,above,font=\tiny] {$\delta$};")
    xa0 = -rf_a * DX
    L.append(f"\\draw[cfA,line width=0.6pt,|-|] ({xa0:.3f},{bot - 0.42:.3f}) -- (0,{bot - 0.42:.3f})"
             r" node[midway,below,font=\scriptsize,align=center]"
             r" {audio encoder: 4 causal convs;\\ receptive field 31 samples (0.48\,s) up to $t$};")
    # left annotations
    L.append(f"\\node[font=\\scriptsize,text=cfN,anchor=east,align=right] at ({lo * DX:.3f},{top - 0.6:.3f})"
             r" {neural path\\(future of $t$)};")
    L.append(f"\\node[font=\\scriptsize,text=cfA,anchor=east,align=right] at ({lo * DX:.3f},{bot + 0.4:.3f})"
             r" {acoustic path\\(past of $t$)};")
    L.append(r"\end{tikzpicture}")
    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
